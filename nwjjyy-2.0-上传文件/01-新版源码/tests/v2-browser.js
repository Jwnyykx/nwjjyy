async originalPage => {
  const browser = originalPage.context().browser()
  const first = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const page = await first.newPage()
  const url = 'http://127.0.0.1:5192/'
  const label = '〔V2验收〕' + Date.now()
  const checks = []
  const errors = []
  const open = (target, path) => target.goto(url + '#/' + path)
  const text = (target, name) => target.getByText(name, { exact: true }).first().waitFor({ timeout: 12000 })
  const heading = (target, name) => target.getByRole('heading', { name, exact: true }).first().waitFor({ timeout: 12000 })
  const button = (target, name) => target.getByRole('button', { name, exact: true }).first().click({ timeout: 12000 })
  const link = (target, name) => target.getByRole('link', { name, exact: true }).first().click({ timeout: 12000 })
  const fill = (target, name, value) => target.getByLabel(name, { exact: true }).first().fill(value, { timeout: 12000 })
  const waitPath = (target, path) => target.waitForURL(new RegExp('#/' + path))
  const inspect = target => target.on('pageerror', error => errors.push(error.message))
  async function login(target, email) {
    await heading(target,'成员登录')
    await fill(target, '邮箱', email)
    await fill(target, '密码', 'story-local-only')
    await button(target,'登录并打开故事书')
  }
  async function small(target, description) {
    for (const width of [360, 390, 430, 768, 1440]) {
      await target.setViewportSize({ width, height: 844 })
      if (await target.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)) {
        throw new Error(description + ' overflow at ' + width)
      }
    }
    await target.setViewportSize({ width: 390, height: 844 })
  }
  async function publish(title, hidden = false, withPhoto = false) {
    await open(page,'edit/story/new')
    await heading(page,'写一段新故事')
    await fill(page, '故事标题', title)
    await fill(page, '故事日期', '2025-02-01')
    await fill(page, '正文', '这是模拟内容，不是实际发生过的经历。')
    if (hidden) await page.getByLabel('从目录隐藏，保留成员专属链接').check()
    if (withPhoto) {
      await page.locator('input[type=file]').first().setInputFiles('output/qa-media/test-1.webp')
      await fill(page,'照片说明', label + ' 照片')
      await page.locator('input[type=file]').nth(1).setInputFiles('output/qa-media/silent-test.wav')
      await fill(page,'录音说明', label + ' 声音')
    }
    await button(page,'发布')
    await text(page,'已保存并发布。')
    if (hidden) {
      if (await page.locator('a.story-card').filter({ hasText: title }).count()) throw new Error('Hidden story was shown on the home page')
      return
    }
    const entry = (await page.locator('a.story-card').filter({ hasText: title }).first().getAttribute('href'))?.split('/').pop()
    if (!entry) throw new Error('New story missing from homepage')
    return entry
  }
  inspect(page)
  const second = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const writer = await second.newPage()
  inspect(writer)
  try {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(url)
    await small(page,'cover')
    await page.screenshot({path:'output/v2-cover-mobile.png',fullPage:true})
    await open(page,'gift')
    await login(page,'yangyang@example.test')
    await heading(page,'给你留的一页')
    const story = await publish(label + ' 故事', false, true)
    await publish(label + ' 隐藏', true)
    await open(page, 'memory')
    await heading(page, '随机翻开一页')
    await page.getByRole('link', { name: '翻开这一页', exact: true }).waitFor()
    if (await page.getByText(label + ' 隐藏', {exact:true}).count()) throw new Error('Surprise leaked into random selection')
    await open(page, 'stories/' + story)
    await heading(page, label + ' 故事')
    await button(page, '放大封面')
    await button(page, '翻到背面')
    await button(page, '编辑背面')
    await fill(page, '这张照片的小故事', label + ' 背面')
    await button(page, '保存背面')
    await text(page, label + ' 背面')
    await button(page, '关闭照片')
    await small(page,'story')
    await page.screenshot({path:'output/v2-reader-mobile.png',fullPage:true})
    await open(page,'search')
    await fill(page, '关键词', label + ' 背面')
    await page.route('**/rest/v1/rpc/search_book', route => route.abort(), { times: 1 })
    await button(page,'搜索')
    await button(page,'重试')
    const photoResult = page.locator('.search-results a').first()
    await photoResult.click({ timeout: 12000 })
    await page.locator('dialog[open]').waitFor()
    await button(page,'关闭照片')
    checks.push('story, private album upload, photo note, search after network failure, random')
    await open(page, 'collections')
    await button(page, '新建合集')
    await fill(page, '合集名', label + ' 合集')
    await page.getByLabel(label + ' 照片', { exact: true }).check()
    await button(page, '保存合集')
    await link(page, '打开合集')
    await heading(page, label + ' 合集')
    await button(page, label + ' 照片')
    await button(page, '翻到背面')
    await text(page, label + ' 背面')
    await open(page, 'footprints')
    await heading(page,'我们的足迹')
    await small(page,'map')
    await page.screenshot({path:'output/v2-footprints.png',fullPage:true})
    await button(page, '记下相见')
    await fill(page, '相见标题', label + ' 相见')
    await fill(page, '城市', '成都')
    await fill(page, '相见日期', '2025-02-01')
    await page.getByText(/关联旅行中的故事/).click()
    await page.getByLabel(new RegExp(label.replace(/[.*+?^$(){}|[\]\\]/g,'\\$&') + ' 故事')).check()
    await button(page, '保存相见记录')
    await link(page, label + ' 相见')
    await heading(page, '这一次相见')
    await text(page, label + ' 故事')
    await open(page,'years?year=2025')
    await button(page, '编辑年鉴')
    await fill(page, '年鉴标题', label + ' 年鉴')
    await fill(page, '这一年的话', '这段文字来自测试。')
    await button(page, '保存年鉴')
    await heading(page, label + ' 年鉴')
    checks.push('collection creation, city travel, story association, annual save')
    await open(page,'sounds')
    await text(page,label + ' 声音')
    await button(page,'载入录音')
    await page.locator('audio').waitFor()
    if (!(await page.locator('audio').evaluate(node => node.paused))) throw new Error('Audio auto-played')
    await open(page,'letters?write=1&capsule=1')
    await heading(page,'写给未来的你')
    await fill(page,'标题',label + ' 胶囊')
    await fill(page,'正文',label + ' 未开启的内容')
    await page.locator('input[type=datetime-local]').fill('2090-05-01T12:00')
    await page.locator('input[type=file]').first().setInputFiles('output/qa-media/test-1.webp')
    await text(page,'test-1.webp')
    await button(page,'寄出')
    await button(page,'确认寄出')
    await page.locator('.letter-list-card').filter({ hasText: label + ' 胶囊' }).click({ timeout: 12000 })
    await heading(page,label + ' 胶囊')
    const mail = new URL(page.url()).hash.split('?')[1]
    const letterId = new URLSearchParams(mail).get('id')
    if (!letterId) throw new Error('No letter ID')
    await button(page,'查看信里的照片')
    const [attachment] = await Promise.all([
      page.waitForEvent('download'),
      link(page,'保存附件'),
    ])
    if (!attachment.suggestedFilename().endsWith('.webp') || await attachment.failure()) throw new Error('Letter attachment download failed')
    await open(writer,'letters?id=' + letterId)
    await login(writer,'wanwan@example.test')
    await waitPath(writer,'letters\\?id=' + letterId)
    await heading(writer,'一份留给你的时间胶囊')
    if (await writer.getByText(label + ' 未开启的内容', { exact:true }).count()) throw new Error('Locked capsule body appeared')
    await small(writer,'locked capsule')
    await writer.screenshot({path:'output/v2-capsule-mobile.png',fullPage:true})
    await open(writer,'post')
    await writer.getByRole('link', { name: /去信箱看看|封新信/ }).click()
    await heading(writer,'写给你的信')
    checks.push('private sound, scheduled letter attachment, gated NFC link and recipient')
    if (errors.length) throw new Error(JSON.stringify(errors))
    return { checks, errors }
  } finally {
    await second.close()
    await first.close()
  }
}
