async page => {
  const root = 'http://127.0.0.1:5181/'
  const report = { layout: [], actions: [], console: [], failed: [] }
  page.on('pageerror', error => report.console.push(error.message))
  page.on('response', response => {
    const url = new URL(response.url())
    if (url.origin === root.slice(0, -1) && response.status() >= 400 && response.status() !== 409) {
      report.failed.push(response.status() + ' ' + url.pathname)
    }
  })
  page.on('dialog', dialog => { void dialog.accept().catch(() => {}) })
  const timeout = 8000
  const visible = locator => locator.waitFor({ timeout })
  const heading = name => visible(page.getByRole('heading', { name, exact: true }).first())
  const click = (name, role = 'button') => page.getByRole(role, { name, exact: true }).first().click({ timeout })
  const goto = path => page.goto(root + '#/' + path)
  const testName = '〔流程测试〕三张测试图 ' + Date.now()
  async function login(target, email) {
    await target.getByLabel('邮箱', { exact: true }).fill(email, { timeout })
    await target.getByLabel('密码', { exact: true }).fill('story-local-only')
    await target.getByRole('button', { name: '登录并打开故事书', exact: true }).click()
  }
  async function layout(label) {
    for (const width of [360, 390, 430, 768, 1440]) {
      await page.setViewportSize({ width, height: 844 })
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
      if (overflow) throw new Error('Overflow ' + label + ' at ' + width)
    }
    await page.setViewportSize({ width: 390, height: 844 })
    report.layout.push(label)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await goto('stories')
  await heading('成员登录')
  await login(page, 'yangyang@example.test')
  await heading('我们的故事')
  await layout('timeline')
  await click('写故事', 'link')
  await heading('写一段新故事')
  await page.getByLabel('故事标题').fill(testName)
  await page.getByLabel('故事日期').fill('2026-01-10')
  await page.getByRole('textbox', { name: '正文', exact: true }).fill('这是一条明确标记的本机测试。\n\n**加粗排版**与照片不会上传到正式网站。')
  await page.locator('input[type=file]').first().setInputFiles(['output/qa-media/test-1.webp', 'output/qa-media/test-2.webp', 'output/qa-media/test-3.webp'])
  for (let i = 0; i < 3; i++) await page.getByLabel('照片说明', { exact: true }).nth(i).fill('测试图 ' + (i + 1))
  await page.getByRole('button', { name: '插入正文', exact: true }).first().click()
  await page.getByRole('button', { name: '下移第 1 份媒体', exact: true }).click()
  await page.locator('input[type=file]').nth(1).setInputFiles('output/qa-media/silent-test.wav')
  await page.getByRole('button', { name: '预览', exact: true }).click()
  await visible(page.locator('.editor-preview img'))
  await page.getByRole('button', { name: '返回编辑', exact: true }).click()
  await layout('editor')
  await page.screenshot({ path: 'output/editor-mobile.png', fullPage: true })
  const blockPreview = route => {
    if (route.request().method() === 'POST') return route.abort('failed')
    return route.continue()
  }
  await page.route('**/storage/v1/object/**/preview', blockPreview)
  await click('保存草稿')
  await visible(page.getByRole('alert').getByText('上传时网络断开了。可以重试。', { exact: true }))
  await page.unroute('**/storage/v1/object/**/preview', blockPreview)
  await click('保存草稿')
  await heading('管理中心')
  await visible(page.getByText('草稿已保存到故事书。'))
  const editHref = await page.locator('.manage-list li').filter({ hasText: testName }).getByRole('link').getAttribute('href')
  const id = editHref.split('/').pop()
  const second = await page.context().browser().newContext({ viewport: { width: 390, height: 844 }, acceptDownloads: true })
  const writer = await second.newPage()
  writer.on('pageerror', error => report.console.push(error.message))
  try {
    await writer.goto(root + '#/stories/' + id)
    await writer.getByRole('heading', { name: '成员登录', exact: true }).waitFor({ timeout })
    await login(writer, 'wanwan@example.test')
    await writer.getByRole('heading', { name: '这一页暂时无法阅读', exact: true }).waitFor({ timeout })
    report.actions.push('draft hidden from writer')
    await page.goto(root + editHref)
    await heading('编辑故事')
    if (await page.getByLabel('照片说明', { exact: true }).count() !== 3) throw new Error('Draft media missing')
    await click('发布')
    await heading(testName)
    await visible(page.getByText('已保存并发布。'))
    await page.reload()
    await heading(testName)
    await layout('published story')
    await page.getByRole('button', { name: '放大封面' }).click()
    await visible(page.locator('dialog[open] img'))
    await click('下一张照片')
    await visible(page.locator('dialog[open] img'))
    await click('关闭照片')
    await click('载入录音')
    await visible(page.locator('.audio-row audio'))
    await page.locator('audio').evaluate(audio => {
      if (!audio.paused) throw new Error('Audio started automatically')
      return audio.play()
    })
    await page.locator('audio').evaluate(audio => audio.pause())
    await page.screenshot({ path: 'output/reading-mobile.png', fullPage: true })
    await writer.reload()
    await writer.getByRole('heading', { name: testName, exact: true }).waitFor({ timeout })
    if (await writer.getByRole('link', { name: '编辑', exact: true }).count()) throw new Error('Writer has editor for someone else')
    await writer.getByRole('button', { name: '写下我的视角', exact: true }).click()
    await writer.getByLabel('宛宛（测试）的视角').fill('〔流程测试〕第二个账号补充的一段话。')
    await writer.getByRole('button', { name: '保存视角', exact: true }).click()
    await writer.getByText('〔流程测试〕第二个账号补充的一段话。', { exact: true }).waitFor({ timeout })
    report.actions.push('upload retry + publish + reload + second session + perspective + lightbox + audio')
    await page.reload()
    await visible(page.getByText('〔流程测试〕第二个账号补充的一段话。'))
    await click('编辑', 'link')
    await heading('编辑故事')
    const revised = testName + '（改过）'
    await page.getByLabel('故事标题').fill(revised)
    await click('保存更新')
    await heading(revised)
    await click('移到回收站')
    await heading('我们的故事')
    await writer.reload()
    await writer.getByRole('heading', { name: '这一页暂时无法阅读', exact: true }).waitFor({ timeout })
    await goto('manage')
    await heading('管理中心')
    await click('回收站')
    await page.locator('.manage-list li').filter({ hasText: revised }).getByRole('button', { name: '恢复', exact: true }).click({ timeout })
    await visible(page.getByText('记录已恢复。'))
    await writer.reload()
    await writer.getByRole('heading', { name: revised, exact: true }).waitFor({ timeout })
    report.actions.push('editing + trash + restore')
    await goto('album')
    await heading('回忆相册')
    await visible(page.locator('.album-grid img').first())
    await layout('album')
    await page.screenshot({ path: 'output/album-mobile.png', fullPage: true })
    await writer.goto(root + '#/edit/diary/new')
    await writer.getByRole('heading', { name: '写一句今天的心情' }).waitFor({ timeout })
    await writer.getByRole('textbox', { name: '正文', exact: true }).fill('〔流程测试〕这是一条由共同记录者写下的日记。')
    await writer.getByRole('button', { name: '发布', exact: true }).click()
    await writer.getByText('〔流程测试〕这是一条由共同记录者写下的日记。', { exact: true }).waitFor({ timeout })
    await goto('book')
    await visible(page.getByText('〔流程测试〕这是一条由共同记录者写下的日记。'))
    await layout('member home')
    await page.screenshot({ path: 'output/home-mobile-test.png', fullPage: true })
    await click('书页里的小伙伴')

    await click('摸摸小兔子')
    await visible(page.getByText('你咋这样！', { exact: true }))
    await click('摸摸小兔子')
    await click('摸摸小兔子')
    await visible(page.getByText('被你发现啦！', { exact: true }))
    report.actions.push('writer diary + member home + original bunny')
    await goto('settings')
    await heading('故事书设置')
    await layout('settings')
    await click('添加')
    await page.getByLabel('纪念日名称').fill('〔流程测试〕纪念日')
    await page.locator('.settings-section').getByLabel('日期', { exact: true }).fill('2026-01-10')
    await click('保存纪念日')
    await heading('〔流程测试〕纪念日')
    await goto('promises')
    await heading('未来的约定')
    await click('写下约定')
    const promiseTitle = '〔流程测试〕新约定 ' + Date.now()
    await page.getByLabel('约定标题').fill(promiseTitle)
    await click('标记今天完成')
    await page.getByLabel('关联回忆（选填）').selectOption(id)
    await click('保存约定')
    await heading(promiseTitle)
    await visible(page.getByRole('link', { name: '翻开回忆 · ' + revised, exact: true }))
    report.actions.push('anniversary + completed promise linked to story')
    await goto('export')
    await heading('备份与导出')
    await click('准备备份')
    for (const [name, pattern, path] of [
      ['下载记录 JSON', /^nwjjyy-records-.*\.json$/, 'output/e2e-backup.json'],
      [/下载媒体第 1 批/, /^nwjjyy-media-.*-1\.zip$/, 'output/e2e-media-1.zip'],
    ]) {
      const event = page.waitForEvent('download', { timeout })
      await page.getByRole('button', { name }).click({ timeout })
      const download = await event
      if (!pattern.test(download.suggestedFilename())) throw new Error('Unexpected backup filename')
      await download.saveAs(path)
    }
    report.actions.push('JSON + media ZIP downloaded')
    const unauthorized = await page.context().browser().newContext()
    try {
      const stranger = await unauthorized.newPage()
      await stranger.goto(root + '#/stories/' + id)
      await login(stranger, 'visitor@example.test')
      await stranger.getByText('当前账号尚未获得阅读权限，请联系管理员。', { exact: true }).waitFor({ timeout })
    } finally { await unauthorized.close() }
    await goto('more')
    await click('退出登录')
    await visible(page.getByRole('link', { name: '打开故事书', exact: true }))
    report.actions.push('authenticated nonmember refused + sign out')
    if (report.console.length || report.failed.length) throw new Error(JSON.stringify(report))
    await page.screenshot({ path: 'output/browser-flow-finished.png' })
    console.log(JSON.stringify(report)); return report
  } finally {
    await second.close()
  }
}
